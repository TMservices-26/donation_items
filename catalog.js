const catalogView = document.querySelector("#catalog-view");
const detailView = document.querySelector("#detail-view");
const itemGrid = document.querySelector("#item-grid");
const searchInput = document.querySelector("#search-input");
const categoryFilter = document.querySelector("#category-filter");
const locationFilter = document.querySelector("#location-filter");
const resultCount = document.querySelector("#result-count");
const emptyState = document.querySelector("#empty-state");

function addOptions(select, values) {
  for (const value of values) {
    const option = document.createElement("option");
    option.value = value;
    option.textContent = value;
    select.append(option);
  }
}

function makeItemCard(item) {
  const link = document.createElement("a");
  link.className = "item-card";
  link.href = `?item=${encodeURIComponent(item.id)}`;

  const category = document.createElement("span");
  category.className = "item-category";
  category.textContent = item.category;

  const name = document.createElement("h2");
  name.textContent = item.name;

  const location = document.createElement("p");
  location.className = "item-location";
  location.textContent = `Location: ${item.location}`;

  if (item.images.length > 0) {
    const image = document.createElement("img");
    image.className = "item-image";
    image.src = item.images[0];
    image.alt = item.name;
    link.append(image);
  }

  const quantity = document.createElement("p");
  quantity.className = "item-quantity";
  quantity.textContent = item.quantity === null
    ? "Quantity not specified"
    : `Quantity: ${item.quantity}`;

  const action = document.createElement("span");
  action.className = "item-action";
  action.textContent = "View details";

  link.append(category, name, location, quantity, action);
  return link;
}

function renderItems() {
  const query = searchInput.value.trim().toLowerCase();
  const visibleItems = items.filter((item) => {
    const matchesSearch = `${item.name} ${item.category} ${item.location} ${item.ticketNumber} ${item.quantity ?? ""}`
      .toLowerCase()
      .includes(query);
    const matchesCategory = !categoryFilter.value || item.category === categoryFilter.value;
    const matchesLocation = !locationFilter.value || item.location === locationFilter.value;
    return matchesSearch && matchesCategory && matchesLocation;
  });

  itemGrid.replaceChildren(...visibleItems.map(makeItemCard));
  resultCount.textContent = `${visibleItems.length} ${visibleItems.length === 1 ? "item" : "items"}`;
  emptyState.hidden = visibleItems.length > 0;
}

function renderDetail(item) {
  catalogView.hidden = true;
  detailView.hidden = false;
  document.title = `${item.name} | Des Moines Donatable Items Catalog`;

  const backLink = document.createElement("a");
  backLink.className = "back-link";
  backLink.href = "./";
  backLink.textContent = "Back to catalog";

  const category = document.createElement("p");
  category.className = "eyebrow";
  category.textContent = item.category;

  const heading = document.createElement("h1");
  heading.textContent = item.name;

  const location = document.createElement("p");
  location.className = "detail-location";
  location.textContent = `Location: ${item.location}`;

  const quantity = document.createElement("p");
  quantity.className = "detail-description";
  quantity.textContent = item.quantity === null
    ? "Quantity: Not specified"
    : `Quantity: ${item.quantity}`;

  const description = document.createElement("p");
  description.className = "detail-description";
  description.textContent = item.description ?? "";

  const ticket = document.createElement("p");
  ticket.className = "detail-description";
  ticket.textContent = `Ticket number: ${item.ticketNumber}`;

  const panel = document.createElement("article");
  panel.className = "detail-panel";
  panel.append(category, heading, location, quantity);
  if (item.description) {
    panel.append(description);
  }
  panel.append(ticket);
  if (item.images.length > 0) {
    const imageGallery = document.createElement("div");
    imageGallery.className = "detail-images";
    imageGallery.setAttribute("aria-label", "Item photos");
    for (const [index, source] of item.images.entries()) {
      const image = document.createElement("img");
      image.src = source;
      image.alt = `${item.name} photo ${index + 1}`;
      imageGallery.append(image);
    }
    panel.append(imageGallery);
  }
  detailView.append(backLink, panel);
}

function renderNotFound() {
  catalogView.hidden = true;
  detailView.hidden = false;

  const heading = document.createElement("h1");
  heading.textContent = "Item not found";

  const message = document.createElement("p");
  message.textContent = "That item may have been removed from the catalog.";

  const backLink = document.createElement("a");
  backLink.className = "back-link";
  backLink.href = "./";
  backLink.textContent = "Back to catalog";

  detailView.append(heading, message, backLink);
}

const selectedItemId = new URLSearchParams(window.location.search).get("item");
if (selectedItemId) {
  const selectedItem = items.find((item) => item.id === selectedItemId);
  if (selectedItem) {
    renderDetail(selectedItem);
  } else {
    renderNotFound();
  }
} else {
  addOptions(categoryFilter, [...new Set(items.map((item) => item.category))].sort());
  addOptions(locationFilter, [...new Set(items.map((item) => item.location))].sort());
  renderItems();

  searchInput.addEventListener("input", renderItems);
  categoryFilter.addEventListener("change", renderItems);
  locationFilter.addEventListener("change", renderItems);
}
